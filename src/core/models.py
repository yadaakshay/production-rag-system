"""Domain entities and Pydantic models for the RAG pipeline."""

from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field
import uuid
import time


class Document(BaseModel):
    """Represents an ingested document prior to chunking."""
    doc_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    text: str = Field(..., description="Raw text content of the document")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Metadata like filename, author, date, page")

    def __repr__(self) -> str:
        return f"<Document id={self.doc_id[:8]} chars={len(self.text)} metadata={self.metadata.get('source', 'unknown')}>"


class Chunk(BaseModel):
    """Represents a discrete segmented unit of text with provenance metadata."""
    chunk_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    doc_id: str = Field(..., description="ID of the parent document")
    text: str = Field(..., description="Chunk text content")
    chunk_index: int = Field(default=0, description="Sequential index within document")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Inherited and enriched metadata")
    token_count: Optional[int] = Field(default=None, description="Approximated or exact token count")
    embedding: Optional[List[float]] = Field(default=None, description="Dense embedding vector")

    def __repr__(self) -> str:
        return f"<Chunk id={self.chunk_id[:8]} doc={self.doc_id[:8]} len={len(self.text)} index={self.chunk_index}>"


class RetrievalResult(BaseModel):
    """Represents a candidate chunk retrieved by search mechanisms."""
    chunk: Chunk
    score: float = Field(..., description="Retrieval score (similarity, BM25 score, RRF, or Cross-Encoder logit)")
    rank: int = Field(default=1, description="Rank position in result set")
    retriever_name: str = Field(default="unknown", description="Which component retrieved this: dense, sparse, hybrid, reranker")

    def __repr__(self) -> str:
        return f"<RetrievalResult rank={self.rank} score={self.score:.4f} retriever={self.retriever_name} chunk={self.chunk.chunk_id[:8]}>"


class QueryTransformationResult(BaseModel):
    """Results from query rewriting, decomposition, or HyDE expansion."""
    original_query: str
    transformed_queries: List[str]
    transformation_type: str  # 'direct', 'hyde', 'multi_query', 'route'
    metadata: Dict[str, Any] = Field(default_factory=dict)


class Citation(BaseModel):
    """Provenance citation linking a claim to a source chunk."""
    source_chunk_id: str
    source_document: str
    chunk_index: int
    snippet: str


class RAGResponse(BaseModel):
    """End-to-end response generated by the RAG orchestrator."""
    query: str
    answer: str
    retrieved_chunks: List[RetrievalResult] = Field(default_factory=list)
    citations: List[Citation] = Field(default_factory=list)
    latency_breakdown: Dict[str, float] = Field(default_factory=dict)
    token_usage: Dict[str, int] = Field(default_factory=dict)
    faithfulness_score: Optional[float] = None
    query_transformations: Optional[QueryTransformationResult] = None
    created_at: float = Field(default_factory=time.time)


class EvaluationMetricResult(BaseModel):
    """Metric evaluation score for a single question-answer sample."""
    query: str
    generated_answer: str
    ground_truth: Optional[str] = None
    contexts: List[str] = Field(default_factory=list)
    faithfulness: Optional[float] = None
    answer_relevance: Optional[float] = None
    context_precision: Optional[float] = None
    context_recall: Optional[float] = None
    hit_rate: Optional[int] = None
    reciprocal_rank: Optional[float] = None


class RAGBenchmarkResult(BaseModel):
    """Aggregated benchmark metrics across an evaluation dataset."""
    pipeline_mode: str
    num_samples: int
    avg_latency_ms: float
    mean_faithfulness: float
    mean_answer_relevance: float
    mean_context_precision: float
    mean_context_recall: float
    mean_mrr: float
    mean_hit_rate: float
